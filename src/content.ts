export function priceOf(offer: ShopOffer, level: number): number {
  if (offer.kind === "spell") return offer.basePrice;
  return Math.round(offer.basePrice * (1 + level * 0.75));
}

export function statBlock(upgrades: Record<string, number>) {
  const d = upgrades.dmg ?? 0;
  const r = upgrades.rate ?? 0;
  const h = upgrades.hp ?? 0;
  const s = upgrades.spd ?? 0;
  const g = upgrades.rng ?? 0;
  const m = upgrades.mana ?? 0;
  return {
    damage: 1 + 0.15 * d,
    fire: 1 + 0.12 * r,
    maxHp: 100 + 20 * h,
    speed: 142 * (1 + 0.08 * s),
    range: 1 + 0.15 * g,
    maxMana: 100 + 20 * m,
  };
}
